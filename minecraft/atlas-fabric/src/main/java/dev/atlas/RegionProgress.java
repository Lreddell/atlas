package dev.atlas;

import net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents;
import net.fabricmc.fabric.api.networking.v1.ServerPlayConnectionEvents;
import net.minecraft.block.Blocks;
import net.minecraft.server.world.ServerWorld;
import net.minecraft.text.Text;
import net.minecraft.util.math.*;
import net.minecraft.world.World;

/** World-owned region milestones; discoveries are player tags and survive respawn. */
public final class RegionProgress {
  public static void init() {
    ServerPlayConnectionEvents.JOIN.register(
        (handler, sender, server) -> {
          var p = handler.player;
          if (p.addCommandTag("atlas:journal"))
            p.sendMessage(
                Text.literal(
                    "Atlas · Press J for your field journal. C dodges; F5 changes the camera."
                        + " /atlas guide lists the controls."),
                false);
        });
    ServerTickEvents.END_WORLD_TICK.register(
        w -> {
          if (w.getRegistryKey() != World.OVERWORLD || w.getTime() % 40 != 0) return;
          for (var p : w.getPlayers()) {
            if (w.getBiome(p.getBlockPos()).matchesKey(Worldgen.FIELDS)
                && p.addCommandTag("atlas:discovered_fields")) {
              p.sendMessage(
                  Text.literal(
                      "Discovered · Magnetic Fields. Terraced magnetite surrounds four axis towers."
                          + " Press J to read your field notes."),
                  false);
            }
            var site = Vaults.at(w, p.getBlockPos());
            if (site != null
                && Vaults.inside(site, p.getBlockPos())
                && p.addCommandTag("atlas:discovered_vault"))
              p.sendMessage(
                  Text.literal(
                      "Discovered · Resonant Vault. Read its stones, open the armory caches and"
                          + " explore both circuits."),
                  false);
          }
        });
  }

  public static void victory(ServerWorld w, AtlasBoss boss) {
    // Only replace encounter-owned crystal blocks. Player builds and surrounding
    // terrain are never regenerated by a victory or rematch.
    for (int i = 0; i < 4; i++) {
      var at = boss.tower(i);
      if (w.isChunkLoaded(at) && w.getBlockState(at).isOf(Content.block("magnetic_shield_crystal")))
        w.setBlockState(at, Blocks.END_ROD.getDefaultState());
    }
    for (var p : w.getPlayers())
      if (p.squaredDistanceTo(Vec3d.ofCenter(boss.anchor())) < 180 * 180) {
        p.sendMessage(
            Text.literal(
                "The Meridian settles. This field is unsealed for building. The fallen Warden"
                    + " leaves a boots upgrade; craft upgraded boots to wield Warden Field with"
                    + " G."),
            false);
      }
  }
}
