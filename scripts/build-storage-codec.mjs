// Electron main has no TypeScript loader. Compile the pure shared palette codec
// deterministically so browser workers and Electron use the same content keys.
import { build } from 'esbuild';
await build({
    entryPoints: ['src/systems/world/storage/contentCodec.ts'],
    outfile: 'electron/saves/paletteCore.cjs',
    bundle: true,
    format: 'cjs',
    platform: 'neutral',
    target: 'es2022',
    banner: { js: '// Generated by scripts/build-storage-codec.mjs. Edit the TypeScript source.' },
});
